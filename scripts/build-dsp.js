// Compiles the synth voices written in Faust (src/audio/faust/dsp/*.dsp) to WebAssembly, ahead of time, with the Faust
// compiler's own WebAssembly build (@grame/faustwasm, a dev dependency: nothing of it ships). Writes one .wasm per
// voice and layout.js, which says where each control lives in a voice's memory, into src/audio/faust/generated/. The
// output is committed, so a normal build and CI never need the compiler. Run after changing a .dsp file:
//   npm run dsp
// See docs/adr/0011-synth-voices-in-faust.md.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { FaustCompiler, LibFaust, instantiateFaustModuleFromFile } from '@grame/faustwasm/dist/esm/index.js';
import prettier from 'prettier';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SOURCE = path.join(ROOT, 'src/audio/faust/dsp');
const OUTPUT = path.join(ROOT, 'src/audio/faust/generated');
/** Inside the compiler's own in-memory file system, where it looks for bpm.lib. */
const INCLUDE = '/bpmachina';
// Flush denormal numbers to zero: a decaying filter would otherwise slow the audio thread down as it fades out.
const OPTIONS = `-ftz 2 -I ${INCLUDE}`;

/**
 * @typedef {{ size: number, outputs: number, imports: string[], params: Record<string, number> }} Layout `size`: bytes
 *   the voice's state takes at the start of its memory; `params`: each control's byte offset; `imports`: the maths
 *   functions the module asks its host for
 */

/**
 * @param {any[]} items the `ui` tree of a compiled voice's JSON
 * @param {Record<string, number>} params filled with label → byte offset
 * @returns {Record<string, number>}
 */
function collectParams(items, params = {}) {
  for (const item of items) {
    if (item.items) {
      collectParams(item.items, params);
    } else if (typeof item.index === 'number') {
      params[item.label] = item.index;
    }
  }
  return params;
}

async function main() {
  const faustModule = await instantiateFaustModuleFromFile(
    fileURLToPath(new URL('../node_modules/@grame/faustwasm/libfaust-wasm/libfaust-wasm.js', import.meta.url)),
  );
  const compiler = new FaustCompiler(new LibFaust(faustModule));
  const files = compiler.fs();
  files.mkdir(INCLUDE);
  const sources = await readdir(SOURCE);
  for (const name of sources.filter((file) => file.endsWith('.lib'))) {
    files.writeFile(`${INCLUDE}/${name}`, await readFile(path.join(SOURCE, name), 'utf8'));
  }

  /** @type {Record<string, Layout>} */
  const layouts = {};
  for (const file of sources.filter((name) => name.endsWith('.dsp')).sort()) {
    const name = path.basename(file, '.dsp');
    const code = await readFile(path.join(SOURCE, file), 'utf8');
    const factory = await compiler.createMonoDSPFactory(name, code, OPTIONS);
    if (!factory) {
      throw new Error(`${file}: ${compiler.getErrorMessage()}`);
    }
    const json = JSON.parse(factory.json);
    if (json.outputs !== 2 || json.inputs !== 0) {
      throw new Error(`${file}: a voice takes no input and plays in stereo, two outputs`);
    }
    const module = new WebAssembly.Module(factory.code);
    layouts[name] = {
      size: json.size,
      outputs: json.outputs,
      imports: WebAssembly.Module.imports(module).map((entry) => entry.name),
      params: collectParams(json.ui),
    };
    await writeFile(path.join(OUTPUT, `${name}.wasm`), factory.code);
    console.log(`${name}: ${factory.code.length} bytes, ${Object.keys(layouts[name].params).length} controls`);
  }

  const source = `// Generated by scripts/build-dsp.js from src/audio/faust/dsp with Faust ${compiler.version()}. Do not edit:
// change the .dsp file and run \`npm run dsp\`.

/** @type {Record<string, { size: number, outputs: number, imports: string[], params: Record<string, number> }>} */
export const DSP_LAYOUTS = ${JSON.stringify(layouts)};
`;
  const target = path.join(OUTPUT, 'layout.js');
  const options = (await prettier.resolveConfig(target)) ?? {};
  await writeFile(target, await prettier.format(source, { ...options, filepath: target }));
}

main().catch((error) => {
  console.error(`Faust build failed: ${error.message}`);
  process.exitCode = 1;
});
